#!/usr/bin/env python3
"""Generate an instruction-level model module from an ADI listing of FX core 2 routines.

The listing is the output of `tools/adi_dis.py` over the core 2 SRAM image (offset 0 = pc
`0x120000`). Each routine of `ROUTINES` becomes one function of straight-line `step(...)` calls
for `tools/fx_leslie_ops.py` (the translator of `tools/fx_leslie_gen.py` does the instruction
parsing); it carries instruction semantics only, no data words. The checked-in models
(`tools/fx_model_mod2_gen.py`) are the output of this tool; the oracle check is
`tools/fx_models.py`.

    python tools/adi_dis.py SRAM/core2_sram.bin 0x240000 0x250000 > core2.txt
    python tools/fx_listing_gen.py core2.txt > tools/fx_model_mod2_gen.py
    python tools/fx_listing_gen.py core2.txt --check      # exit 1 when the file is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent))
import fx_leslie_gen as lg

OUT = Path(__file__).resolve().parent / "fx_model_mod2_gen.py"
#: Routine name -> (first pc, last pc) on FX core 2 (OS v1.66; `docs/research/fx-mod2-types.md`).
ROUTINES = {
    "vibe": (0x123C84, 0x123DB3),
    "flang": (0x12348D, 0x123538),
    "spin": (0x123557, 0x12377C),
    "phas0": (0x12379B, 0x1238FB),
    "phas1": (0x1238FC, 0x1239CF),
    "ens": (0x123A7B, 0x123BCF),
}
HEADER = '''# ruff: noqa: E741, F403, F405, E501
# fmt: off
"""Instruction-level models of the Mod 2 routines (FX core 2), generated.

Generated by `tools/fx_listing_gen.py` from an ADI listing (instruction semantics only):
{names}. Verified against the `sharc-fx` oracle by `tools/fx_models.py`.
"""

from __future__ import annotations

from fx_leslie_ops import *  # noqa: F403
'''


def render(listing: Path) -> str:
    """The model module for `listing` (the translator tracks AV / AC and float flags here only)."""
    lg.AVAC, saved = True, lg.AVAC
    try:
        return _render(lg.parse_listing(listing))
    finally:
        lg.AVAC = saved


def _render(lst: dict[int, tuple[int, str]]) -> str:
    names = ", ".join(f"`{n}` {a:#x}..{b:#x}" for n, (a, b) in ROUTINES.items())
    out = [HEADER.format(names=names)]
    for name, (a, b) in ROUTINES.items():
        out += ["", *lg.gen_routine(lst, a - lg.BASE, b - lg.BASE, name)]
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("listing", type=Path)
    ap.add_argument("--check", action="store_true")
    ns = ap.parse_args(argv)
    text = render(ns.listing)
    if ns.check:
        stale = not OUT.exists() or OUT.read_text(encoding="utf-8") != text
        print("stale" if stale else "up to date")
        return 1 if stale else 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
