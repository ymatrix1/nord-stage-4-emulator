#!/usr/bin/env python3
# ruff: noqa: E501
"""Instance rows, type words and parameter laws of the Mod 1 types 4..11 and the boot words of
three Mod 2 instances, as Rust (derived values, nothing here is firmware code).

Each instance row is the static FX image (core 1 flat SRAM, `tools/ns4_dsp_ldr.py --sram`) under
the words the ARM sends during the boot (`target/bulk/fx_core1.script` of
`python tools/arm_bulk_tables.py capture`): the boot words carry the self pointers, the block
counts and the filter or all-pass gains that no type or parameter write lists
(`docs/research/fx-mod-types.md` s7).

    python tools/fx_mod1_laws.py rows SRAM/core1_sram.bin target/bulk/fx_core1.script
    python tools/fx_mod1_laws.py check SRAM/core1_sram.bin target/bulk/fx_core1.script
    python tools/fx_mod1_laws.py rust [--check]
"""

from __future__ import annotations

import argparse
import csv
import struct
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent))
import fx_mod2_laws as m2

DATA = m2.DATA
ROWS_CSV = DATA / "fx-mod1-rows.csv"
RUST = m2.ROOT / "crates" / "nord-core" / "src" / "fx" / "fw_mod1_data.rs"
#: `I1` of the piano unit instance (`fx-type-words.csv`: first word + 32 for the 32 word windows,
#: or the self pointer word + 31). Mod 1 rows, then three Mod 2 rows completed by the boot words.
BASES = {
    "rm": 0xB04B4,
    "wah": 0xC1884,
    "awah": 0xC1946,
    "pump": 0xC16CA,
    "ens": 0xC129E,
    "spin": 0xC1174,
    "phas1": 0xB0432,
}
#: `kFx1Type` -> routine name
TYPES = {4: "rm", 5: "rm", 6: "awah", 7: "awah", 8: "wah", 9: "wah", 10: "pump", 11: "pump"}
LO, HI = -32, 0x2A


def boot_words(script: Path) -> dict[int, int]:
    """Last value per DM word of a replay script (`0 0xADDR 0xWORD` lines)."""
    out: dict[int, int] = {}
    for line in script.read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if len(parts) == 3:
            out[int(parts[1], 16)] = int(parts[2], 16)
    return out


def row_words(image: bytes, boot: dict[int, int]) -> list[tuple[str, int, int, str]]:
    out = []
    for name, base in BASES.items():
        for off in range(LO, HI + 1):
            img = struct.unpack_from("<I", image, 4 * (base + off))[0]
            word, src = (boot[base + off], "boot") if base + off in boot else (img, "image")
            if word or img:
                out.append((name, off, word, src))
    return out


def read_rows() -> list[tuple[str, int, int, str]]:
    with ROWS_CSV.open(encoding="utf-8") as f:
        return [
            (r["name"], int(r["offset"]), int(r["word"], 16), r["source"])
            for r in csv.DictReader(f)
        ]


def write_rows(rows: list[tuple[str, int, int, str]]) -> None:
    with ROWS_CSV.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["name", "offset", "word", "source"])
        for name, off, word, src in rows:
            w.writerow([name, off, f"{word:#010x}", src])


def type_words() -> dict[int, dict[int, int]]:
    out: dict[int, dict[int, int]] = {t: {} for t in TYPES}
    with (DATA / "fx-type-words.csv").open(encoding="utf-8") as f:
        for r in csv.DictReader(f):
            t = int(r["type"])
            if r["slot"] == "Fx1" and t in TYPES and "piano" in r["kinds"]:
                out[t].setdefault(int(r["ctx"]), int(r["word"], 16))
    return out


def laws() -> dict[int, dict[str, dict[int, tuple[bool, list[int]]]]]:
    out: dict[int, dict[str, dict[int, tuple[bool, list[int]]]]] = {
        t: {"Amt": {}, "Rate": {}} for t in TYPES
    }
    with (DATA / "fx-param-fits.csv").open(encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if r["slot"] != "Fx1" or not r["type"] or int(r["type"]) not in TYPES:
                continue
            if "piano" not in r["kinds"] or r["id"].endswith("ClkEnable"):
                continue
            t = int(r["type"])
            kind = "Amt" if r["id"].endswith("kFx1Amt") else "Rate"
            pts = dict(s.split(":") for s in r["samples"].split(";"))
            words = [int(pts[str(v)], 16) for v in m2.SAMPLES]
            out[t][kind].setdefault(int(r["ctx"]), (r["float"] == "1", words))
    return out


def rust() -> str:
    rows = read_rows()
    tw, lw = type_words(), laws()
    out = [
        "//! Instance rows, type words and parameter laws of the Mod 1 types 4..11 (derived values).",
        "//!",
        "//! GENERATED by `python tools/fx_mod1_laws.py rust` from `docs/research/data/fx-mod1-rows.csv`,",
        "//! `fx-type-words.csv` and `fx-param-fits.csv` (piano rows); do not edit. VERIFIED at the 11",
        "//! captured values of every law, EMPIRICAL between them (linear interpolation). The rows are",
        "//! the static FX image under the words the ARM sends during the boot (VERIFIED: the boot",
        "//! log of `tools/arm_bulk_tables.py capture`); the words of the piano unit are used for",
        "//! every layer (ASSUMED). `ROW_ENS`, `ROW_SPIN`, `ROW_PHAS1` complete the Mod 2 rows.",
        "",
        "use super::fw_mod2_data::Law;",
        "",
    ]
    for name in BASES:
        out.append(
            f"/// Non-zero words of the `{name.upper()}` instance row `c[off]` (image under the boot words)."
        )
        out.append(
            f"pub(super) const ROW_{name.upper()}: &[(i32, u32)] = "
            + m2._pairs({o: w for n, o, w, _ in rows if n == name})
            + ";"
        )
    out.append("")
    for t, name in TYPES.items():
        out.append(f"/// Words the ARM writes at the switch to `kFx1Type` {t} (piano row).")
        out.append(f"pub(super) const WORDS_{t}: &[(i32, u32)] = " + m2._pairs(tw[t]) + ";")
    out.append("")
    for t, name in TYPES.items():
        for kind in ("Amt", "Rate"):
            out.append(f"/// `kFx1{kind}` laws of `kFx1Type` {t} (`{name.upper()}`).")
            out.append(
                f"pub(super) const {kind.upper()}_{t}: &[Law] = " + m2._law_list(lw[t][kind]) + ";"
            )
    text = "\n".join(out) + "\n"
    for p in ("ROW_", "WORDS_", "AMT_", "RATE_"):
        text = text.replace(f"pub(super) const {p}", f"#[rustfmt::skip]\npub(super) const {p}")
    return text


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("cmd", choices=["rows", "check", "rust"])
    ap.add_argument("image", nargs="?")
    ap.add_argument("script", nargs="?")
    ap.add_argument("--check", action="store_true")
    ns = ap.parse_args(argv)
    if ns.cmd == "rust":
        text = rust()
        if ns.check:
            stale = not RUST.exists() or RUST.read_text(encoding="utf-8") != text
            print("stale" if stale else "up to date")
            return 1 if stale else 0
        RUST.write_text(text, encoding="utf-8", newline="\n")
        return 0
    if not ns.image or not ns.script:
        ap.error("image and boot script required")
    rows = row_words(Path(ns.image).read_bytes(), boot_words(Path(ns.script)))
    if ns.cmd == "rows":
        write_rows(rows)
        return 0
    same = rows == read_rows()
    print("rows equal the local image and boot log" if same else "MISMATCH")
    return 0 if same else 1


if __name__ == "__main__":
    sys.exit(main())
