#!/usr/bin/env python3
# ruff: noqa: E501
"""Generate the Rust port of the multi-tap reverb (types 2..11) from `tools/fx_model_rvbmulti.py`.

The model (one `step(pc, ...)` per instruction, verified against the `sharc-fx` oracle by
`tools/fx_rvbmulti_check.py`) is read as a syntax tree, no firmware bytes and no listing, and
turned into straight-line Rust against the register machine of `fw_leslie_core.rs`:

* `fw_rvbm_steps_core.rs`: the packed multi-tap core `0x120D8A` (the `do` loop as a `for` loop),
* `fw_rvbm_steps_wrap.rs`: the wrapper `0x120FDB` (the `CALL 0x120D8A` as `m.rvbm_core()`),
* `fw_rvbm_words.rs`: the derived numeric words (the instance row `docs/research/data/
  fx-rvbmulti-instance.csv`, core 2 row 0, and the ARM type words of types 2..11),
* `tests_fw_rvbm_golden_data.rs`: the oracle fingerprints `fx-rvbmulti-golden.csv`.

    python tools/fx_rvbmulti_rust_gen.py            # rewrite the files
    python tools/fx_rvbmulti_rust_gen.py --check    # exit 1 when a committed file is stale
"""

from __future__ import annotations

import argparse
import ast
import csv
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent))
import fx_leslie_rust_gen as lrg
import fx_rvbmulti as rm

ROOT = Path(__file__).resolve().parents[1]
MODEL = ROOT / "tools" / "fx_model_rvbmulti.py"
FX_DIR = ROOT / "crates" / "nord-core" / "src" / "fx"
DATA = ROOT / "docs" / "research" / "data"
lrg.PAIR_FNS |= {"fpack_p", "funpack_p", "fdep_or", "ibtgl"}


def functions() -> dict[str, list[ast.stmt]]:
    tree = ast.parse(MODEL.read_text(encoding="utf-8"))
    return {n.name: n.body for n in tree.body if isinstance(n, ast.FunctionDef)}


def header(what: str) -> list[str]:
    return [
        f"//! {what}",
        "//!",
        "//! GENERATED by `python tools/fx_rvbmulti_rust_gen.py` from `tools/fx_model_rvbmulti.py`; do not",
        "//! edit. VERIFIED: the model matches the `sharc-fx` oracle on every register before every",
        "//! instruction (`tools/fx_rvbmulti_check.py`, `docs/research/fx-reverb-leslie.md` s13) and",
        "//! `tests_fw_rvbm_golden.rs` checks this port against the oracle fingerprints.",
        "",
        "use super::fw_ext40::Fp;",
        "use super::fw_leslie_core::{Core, V};",
        "",
        "#[allow(",
        "    clippy::too_many_lines,",
        "    clippy::unnecessary_min_or_max,",
        "    clippy::let_and_return,",
        "    clippy::unreadable_literal",
        ")]",
        "impl<F: Fp> Core<F> {",
    ]


class _CallRewrite(ast.NodeTransformer):
    """`core(m)` (the wrapper's `CALL 0x120D8A`) as the `m.call()` the shared emitter knows."""

    def visit_Expr(self, node: ast.Expr) -> ast.Expr:
        c = node.value
        if isinstance(c, ast.Call) and isinstance(c.func, ast.Name) and c.func.id == "core":
            return ast.parse("m.call()").body[0]  # type: ignore[return-value]
        return node


def routine_file(name: str, body: list[ast.stmt], what: str, fn: str, doc: str) -> str:
    body = [_CallRewrite().visit(st) for st in body]
    lines = [ln.replace("m.callee();", "m.rvbm_core();") for ln in lrg.Emit().body(body)]
    uses_v = any("V::" in ln for ln in lines)
    head = header(what)
    if not uses_v:
        head = [ln.replace("{Core, V}", "Core") for ln in head]
    return "\n".join(
        [
            *head,
            f"    /// {doc}",
            "    #[rustfmt::skip]",
            f"    pub(super) fn {fn}(&mut self) {{",
            "        let m = self;",
            *[f"        {ln}" for ln in lines],
            "    }",
            "}",
            "",
            "/// Instructions of the routine per call (each generated line is one instruction).",
            "#[cfg(test)]",
            f"pub(super) const STATIC_STEPS_{name.upper()}: usize = {sum(ln.count('m.tick(') for ln in lines)};",
            "",
        ]
    )


def _rows(items: list[str], pad: str, per: int = 4) -> list[str]:
    return [pad + " ".join(items[k : k + per]) for k in range(0, len(items), per)]


def words_file() -> str:
    inst = [
        (rm.CTX + int(r["ctx"]), int(r["word"], 16))
        for r in csv.DictReader(open(DATA / "fx-rvbmulti-instance.csv", newline=""))
        if r["core"] == "2" and r["row"] == "0"
    ]
    out = [
        "//! The derived numeric words of the multi-tap reverb instance and of types 2..11.",
        "//!",
        "//! GENERATED by `python tools/fx_rvbmulti_rust_gen.py`; do not edit. Addresses are the",
        "//! firmware's DM words (the port keeps them as windows of its own memory). VERIFIED:",
        "//! `INSTANCE` is the static initial DM of the FX image, core 2 row 0 (synth unit L6,",
        "//! `docs/research/data/fx-rvbmulti-instance.csv`); `TYPE_WORDS` are the ARM's words of",
        "//! `kRvbType` (`docs/research/data/fx-type-words.csv`, kind synth, moved onto row 0 of core 2).",
        "//! Type 6 has no captured block and the organ rows are zero in the image: not here.",
        "",
        "/// DM address of the context base `I1` (`c[0]`) of the instance row.",
        f"pub(super) const CTX: u32 = {rm.CTX:#x};",
        "/// First word of the instance row (`c[-32]`).",
        f"pub(super) const ROW: u32 = {rm.ROW:#x};",
        "/// Words of the row (the context plus the tap tables behind it).",
        f"pub(super) const ROW_WORDS: u32 = {rm.ROW_WORDS};",
        "",
        "/// The `kRvbType` values with captured words, in table order.",
        f"pub(super) const TYPES: [usize; {len(rm.TYPES)}] = {list(rm.TYPES)};",
        "",
        "/// Static instance words `(address, word)`.",
        "#[rustfmt::skip]",
        f"pub(super) const INSTANCE: [(u32, u32); {len(inst)}] = [",
        *_rows([f"({a:#x}, {w:#010x})," for a, w in inst], "    "),
        "];",
        "",
    ]
    tw = [rm.type_words(t) for t in rm.TYPES]
    n = max(len(w) for w in tw)
    assert all(len(w) == n for w in tw)
    out += [
        "/// The ARM's words of each type in [`TYPES`] order: `(address, word)`.",
        "#[rustfmt::skip]",
        f"pub(super) const TYPE_WORDS: [[(u32, u32); {n}]; {len(tw)}] = [",
    ]
    for w in tw:
        out += [
            "    [",
            *_rows([f"({a:#x}, {v:#010x})," for a, v in sorted(w.items())], "        "),
            "    ],",
        ]
    out += ["];", ""]
    return "\n".join(out)


def golden_file() -> str:
    rows = list(csv.DictReader(open(DATA / "fx-rvbmulti-golden.csv", newline="")))
    out = [
        "//! Golden fingerprints of the multi-tap reverb: oracle output of `0x120FDB` on the real instance.",
        "//!",
        "//! GENERATED by `python tools/fx_rvbmulti_rust_gen.py` from `docs/research/data/",
        "//! fx-rvbmulti-golden.csv` (`python tools/fx_rvbmulti.py golden`): FNV-1a hash of every output",
        "//! word (`-0` as `+0`), the count of non-zero words and the first call with output.",
        "",
        "pub(super) struct Golden {",
        "    pub rvb_type: usize,",
        "    pub noise: bool,",
        "    pub amount: usize,",
        "    pub calls: usize,",
        "    pub hash: u64,",
        "    pub nonzero: usize,",
        "    pub first: i64,",
        "}",
        "",
        f"pub(super) const GOLDEN: [Golden; {len(rows)}] = [",
    ]
    for r in rows:
        out += [
            "    Golden {",
            f"        rvb_type: {r['type']},",
            f"        noise: {str(r['kind'] == 'noise').lower()},",
            f"        amount: {r['amount']},",
            f"        calls: {r['calls']},",
            f"        hash: {r['hash']},",
            f"        nonzero: {r['nonzero']},",
            f"        first: {r['first']},",
            "    },",
        ]
    out += ["];", ""]
    return "\n".join(out)


def files() -> dict[str, str]:
    fns = functions()
    return {
        "fw_rvbm_steps_core.rs": routine_file(
            "core", fns["core"], "The packed multi-tap reverb core `0x120D8A` as straight-line Rust.",
            "rvbm_core", "The core: two ring buffers of 16:16 packed words, one call per 4 frames.",
        ),
        "fw_rvbm_steps_wrap.rs": routine_file(
            "wrap", fns["wrapper"], "The multi-tap reverb wrapper `0x120FDB` as straight-line Rust.",
            "rvbm_wrapper", "The wrapper: three fs/4 biquads, the core, three more biquads, the mix.",
        ),
        "fw_rvbm_words.rs": words_file(),
        "tests_fw_rvbm_golden_data.rs": golden_file(),
    }  # fmt: skip


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ns = ap.parse_args(argv)
    stale = []
    produced = files()
    for name, text in produced.items():
        path = FX_DIR / name
        if ns.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    print(f"{len(produced)} files")
    if stale:
        print("stale:", ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
