#!/usr/bin/env python3
"""Golden vectors of the generated Mod 2 models (VIBE, FLANG, PHAS) for the Rust ports.

    python tools/fx_golden_mod2_rest.py > crates/nord-core/src/fx/tests_mod2_golden.rs

Each routine runs `CALLS` times on a seeded scenario of `tools/fx_model_mod2.py` with the state
carried between calls (new input frames per call, `BLOCKS` blocks of two stereo frames each). The
delay ring starts from the deterministic sequence of `tools/fx_golden_mod2.py` (`ring_word`,
mirrored in `fw_mod2_run.rs`). Output: the context before the first call and after the last, the
input and output frames of every call, and the ring words that changed (offset, word).
"""

from __future__ import annotations

import random
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent))
import fx_biquad_check as fb
import fx_golden_mod2 as g2
import fx_model_mod2 as mm

CALLS, BLOCKS, SEED = 3, 2, 20260115
CTX_LO, CTX_N = mm.CTX - 0x20, 0x4B
NL = chr(10)
NAMES = {
    "vibe": "VIBE",
    "flang": "FLANG",
    "phas0": "PHAS0",
    "phas1": "PHAS1",
    "ens": "ENS",
    "spin": "SPIN",
}


def words(vals: list[int], per_line: int = 8) -> str:
    rows = [vals[i : i + per_line] for i in range(0, len(vals), per_line)]
    return "\n".join("        " + ", ".join(f"{w:#010x}" for w in r) + "," for r in rows)


def golden(name: str) -> str:
    """The vectors of the first seed whose 3 calls stay finite and moderate (a random context of
    a feedback routine can blow up; the models do not represent overflow)."""
    for attempt in range(200):
        try:
            return run_golden(name, SEED + sum(map(ord, name)) + attempt)
        except (OverflowError, ValueError):
            continue
    raise SystemExit(f"{name}: no stable scenario")


def run_golden(name: str, seed: int) -> str:
    spec = mm.SPECS[name]
    rng = random.Random(seed)
    mem = {**spec.static(), **mm.finite_scenario(spec, rng)}
    mem[mm.CTX + spec.blocks] = BLOCKS
    for k in range(mm.RING_WORDS):
        mem[mm.BUF + k] = g2.ring_word(k)
    if name == "spin":
        for k in range(mm.RING2_WORDS):
            mem[mm.BUF2 + k] = g2.ring_word(k)
    ctx_in = [mem.get(a, 0) for a in range(CTX_LO, CTX_LO + CTX_N)]
    frames_in, frames_out = [], []
    for _ in range(CALLS):
        fin = [fb.bits(rng.uniform(-0.5, 0.5)) for _ in range(4 * BLOCKS)]
        for k, w in enumerate(fin):
            mem[mm.IN_ADDR + k] = w
        mm.run(spec, mem)
        frames_in += fin
        frames_out += [mem[mm.IN_ADDR + k] for k in range(4 * BLOCKS)]
    ctx_out = [mem.get(a, 0) for a in range(CTX_LO, CTX_LO + CTX_N)]
    if any(abs(fb.from_bits(w)) > 1e6 for w in frames_out if (w >> 23) & 0xFF != 0xFF):
        raise OverflowError(name)
    if frames_out == frames_in:  # a vector that leaves the audio alone checks nothing
        raise ValueError(name)
    diff = [
        (k, mem[mm.BUF + k]) for k in range(mm.RING_WORDS) if mem[mm.BUF + k] != g2.ring_word(k)
    ]
    rows = "\n".join(f"        ({k:#x}, {w:#010x})," for k, w in diff)
    diff2 = [
        (k, mem[mm.BUF2 + k])
        for k in range(mm.RING2_WORDS)
        if name == "spin" and mem[mm.BUF2 + k] != g2.ring_word(k)
    ]
    rows2 = "\n".join(f"        ({k:#x}, {w:#010x})," for k, w in diff2)
    return (
        f"pub(super) static {NAMES[name]}: Golden = Golden {{\n"
        f"    ctx_in: &[\n{words(ctx_in)}\n    ],\n"
        f"    frames_in: &[\n{words(frames_in)}\n    ],\n"
        f"    frames_out: &[\n{words(frames_out)}\n    ],\n"
        f"    ctx_out: &[\n{words(ctx_out)}\n    ],\n"
        f"    ring_diff: &[\n{rows}\n    ],\n"
        f"    ring2_diff: &[\n{rows2}\n    ],\n"
        "};\n"
    )


def main() -> int:
    print(
        "//! Firmware parity of the generated Mod 2 routines (`0x123C84` VIBE, `0x12348D` FLANG,\n"
        "//! `0x12379B` and `0x1238FC` PHAS, `0x123A7B` ENS, `0x123557` SPIN): golden vectors.\n"
        "//!\n"
        "//! Derived values only (context, input and output words of 3 calls with the state\n"
        "//! carried, the ring words that changed), generated by\n"
        "//! `python tools/fx_golden_mod2_rest.py > <this file>` from the models that match the\n"
        "//! `sharc-fx` run of the firmware routines word for word\n"
        "//! (`docs/research/fx-mod2-types.md`).\n"
        "\n"
        "/// One routine's vectors.\n"
        "pub(super) struct Golden {\n"
        "    pub(super) ctx_in: &'static [u32],\n"
        "    pub(super) frames_in: &'static [u32],\n"
        "    pub(super) frames_out: &'static [u32],\n"
        "    pub(super) ctx_out: &'static [u32],\n"
        "    pub(super) ring_diff: &'static [(u32, u32)],\n"
        "    pub(super) ring2_diff: &'static [(u32, u32)],\n"
        "}\n"
    )
    for name in NAMES:
        print(golden(name))
    shape = "".join(
        [
            "#[test]" + NL,
            "fn golden_vectors_have_the_documented_shapes() {" + NL,
            "    for v in [&VIBE, &FLANG, &PHAS0, &PHAS1, &ENS, &SPIN] {" + NL,
            f"        assert_eq!(v.ctx_in.len(), {CTX_N});" + NL,
            f"        assert_eq!(v.ctx_out.len(), {CTX_N});" + NL,
            f"        assert_eq!(v.frames_in.len(), {4 * BLOCKS * CALLS});" + NL,
            f"        assert_eq!(v.frames_out.len(), {4 * BLOCKS * CALLS});" + NL,
            "    }" + NL,
            "}",
        ]
    )
    print(shape)
    return 0


if __name__ == "__main__":
    sys.exit(main())
