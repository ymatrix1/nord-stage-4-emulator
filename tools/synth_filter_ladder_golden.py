#!/usr/bin/env python3
"""Rust data files of the Ladder24 filter stage `0x12549D` (`synth/fw_ladder*` in nord-core).

    python tools/synth_filter_ladder_golden.py tables > \
        crates/nord-core/src/synth/fw_ladder_tables.rs
    python tools/synth_filter_ladder_golden.py golden > \
        crates/nord-core/src/synth/tests_fw_ladder_golden.rs
    cargo fmt -p nord-core

`tables` turns the derived CSVs of `docs/research/data/` (float32 words of the coefficient rows and
the shaper read from the Core2 image) into `u32` arrays. `golden` runs the bit-exact model
`synth_filter_ladder.py` (equal to the oracle, `synth_filter_ladder_oracle.py`) over fixed rows and
prints coefficient words and output words for the Rust float32 port. Everything printed is derived.
"""

from __future__ import annotations

import math
import struct
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent))
import synth_filter_ladder as lad

# Golden rows: (cutoff position word, resonance word); low, mid and high resonance, high cutoff.
ROWS = (
    (0x3E99999A, 0x08000000),
    (0x3F000000, 0x30000000),
    (0x3F19999A, 0x50000000),
    (0x3F4CCCCD, 0x68000000),
    (0x3DCCCCCD, 0x7C000000),
)
SAMPLES = 64


def f2u(x: float) -> int:
    """Float32 bit pattern of `x`."""
    return struct.unpack("<I", struct.pack("<f", x))[0]


def input_words() -> list[int]:
    """Fixed test input: a decaying two tone burst (words)."""
    return [
        f2u(0.8 * math.sin(0.21 * n) + 0.4 * math.sin(1.7 * n + 1.0)) if n < 40 else 0
        for n in range(SAMPLES)
    ]


def fmt_words(name: str, words: list[int], per_line: int = 8) -> str:
    """A `pub(super) const NAME: [u32; N]` item."""
    rows = "".join(
        "    " + ", ".join(f"{w:#010x}" for w in words[i : i + per_line]) + ",\n"
        for i in range(0, len(words), per_line)
    )
    return f"pub(super) const {name}: [u32; {len(words)}] = [\n{rows}];\n"


def tables() -> str:
    """The Rust table file."""
    head = (
        "//! Derived tables of the Ladder24 stage `0x12549D`: coefficient rows 0, 1, 2, 4\n"
        "//! (129 words each)\n"
        "//! and the shaper (1025 words, `DM(0xC02DE + i)`, `i = -512..512`).\n//!\n"
        "//! Generated by `python tools/synth_filter_ladder_golden.py tables` from\n"
        "//! `docs/research/data/synth-ladder-coef-table.csv` and `synth-ladder-shaper-table.csv`\n"
        "//! (float32 words of the ORG core 2 image, derived values only). VERIFIED: the model\n"
        "//! that uses them equals the oracle word for word\n"
        "//! (`docs/research/synth-stage-models-9.md`).\n\n"
    )
    out = head
    for k, name in enumerate(("ROW0", "ROW1", "ROW2", "ROW4")):
        out += fmt_words(name, lad.ROWS[k]) + "\n"
    out += fmt_words("SHAPER", lad.SHAPER)
    out += """
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_have_the_documented_shape() {
        assert_eq!(f32::from_bits(ROW0[0]), f32::from_bits(0x3a05_8d48));
        assert_eq!(SHAPER[512], 0, "T(0) = 0");
        assert_eq!(
            f32::from_bits(SHAPER[513]),
            -f32::from_bits(SHAPER[511]),
            "odd symmetry"
        );
        assert!(f32::from_bits(SHAPER[1024]) > 0.63);
    }
}
"""
    return out


def golden() -> str:
    """The Rust golden test file."""
    xs = input_words()
    out = (
        "//! Firmware parity of the Ladder24 stage `0x12549D` (`fw_ladder.rs`).\n//!\n"
        "//! Generated by `python tools/synth_filter_ladder_golden.py golden` from the bit-exact\n"
        "//! model `tools/synth_filter_ladder.py` (equal to the SHARC oracle). Do not edit by\n"
        "//! hand.\n\n"
        "use super::fw_ladder::{FwLadder, LadderCoefs};\n\n"
    )
    out += f"const N: usize = {SAMPLES};\n"
    out += "pub(super) const ROWS: [(u32, u32); %d] = [\n" % len(ROWS)
    for a, b in ROWS:
        out += f"    ({a:#010x}, {b:#010x}),\n"
    out += "];\n"
    out += fmt_words("INPUT", xs)
    coef_words: list[int] = []
    outs: list[int] = []
    for w30, w28 in ROWS:
        cf = lad.coefficients(w30, w28)
        coef_words += list(cf)
        ln = lad.Lane()
        seq: list[int] = []
        for i in range(0, SAMPLES, 4):
            seq += lad.process(ln, cf, xs[i : i + 4])
        outs += seq
    out += fmt_words("COEFS", coef_words)
    out += fmt_words("OUTPUT", outs)
    out += """
#[test]
fn coefficient_words_match_the_model() {
    for (r, &(w30, w28)) in ROWS.iter().enumerate() {
        let co = LadderCoefs::from_words(w30, w28);
        let want = &COEFS[4 * r..4 * r + 4];
        let got = [co.b, co.a, co.c, co.kf];
        for k in 0..4 {
            let w = f32::from_bits(want[k]);
            assert!(
                (got[k] - w).abs() <= 2e-6 * w.abs() + 1e-9,
                "row {r} coef {k}: {} vs {w}",
                got[k]
            );
        }
    }
}

#[test]
fn output_matches_the_model_words() {
    for (r, &(_, _)) in ROWS.iter().enumerate() {
        let c = &COEFS[4 * r..4 * r + 4];
        let co = LadderCoefs {
            b: f32::from_bits(c[0]),
            a: f32::from_bits(c[1]),
            c: f32::from_bits(c[2]),
            kf: f32::from_bits(c[3]),
        };
        let mut f = FwLadder::default();
        let mut w = 0.0f32;
        for n in 0..N {
            let y = f.process(f32::from_bits(INPUT[n]), &co);
            w = w.max((y - f32::from_bits(OUTPUT[r * N + n])).abs());
        }
        assert!(w < 2e-5, "row {r}: worst deviation {w}");
    }
}
"""
    return out


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    if args[:1] == ["tables"]:
        sys.stdout.write(tables())
    elif args[:1] == ["golden"]:
        sys.stdout.write(golden())
    else:
        sys.stderr.write(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
