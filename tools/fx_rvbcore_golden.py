#!/usr/bin/env python3
# ruff: noqa: E501
"""Golden vectors of the firmware reverb (types 0 and 1) from the `sharc-fx` oracle.

The routine `0x12417E` on the real instance (`tools/fx_rvbreal.py`: context `0xB27E8`, the ARM's
39 type words, the `kRvbAmt` words) is run for `CALLS` calls (4 stereo frames per call) on an
impulse and on a deterministic noise, for both types. The output words (8 per call, the frames in
place at `IN_ADDR`) are reduced to a 64-bit FNV-1a hash, the number of non-zero words and a few
sample calls: derived numbers only. `crates/nord-core/src/fx/tests_fw_rvb_golden.rs` replays the
inputs through the Rust port and compares the words.

    python tools/fx_rvbcore_golden.py SRAM/core2_sram.bin > crates/nord-core/src/fx/tests_fw_rvb_golden_data.rs

The sign of a zero is not compared (the oracle prints `-0` for a flushed underflow).
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent))
import fx_biquad_check as fb
import fx_rvbreal as rr

CALLS = 3000
SEED = 0x2545F491
#: (type, kRvbAmt, input kind); amount 127 = wet only, 64 = a real mix
CASES = ((0, 127, "impulse"), (0, 64, "noise"), (1, 127, "impulse"), (1, 64, "noise"))
AMT_CSV = Path(__file__).resolve().parents[1] / "docs/research/data/fx-reverb-amt.csv"
FNV_OFFSET, FNV_PRIME, M64 = 0xCBF29CE484222325, 0x100000001B3, (1 << 64) - 1


def amount_words(value: int) -> tuple[int, int]:
    """`(send, dry)` words of `kRvbAmt` `value`, as captured (`fx-reverb-amt.csv`)."""
    with open(AMT_CSV, newline="") as f:
        for r in csv.DictReader(f):
            if int(r["value"]) == value:
                return int(r["wet_word"]), int(r["dry_word"])
    raise KeyError(value)


def noise_words(calls: int) -> list[list[int]]:
    """xorshift32 noise in `[-0.25, 0.25)`, `(v - 2^23) / 2^25` for the top 24 bits `v`: exact in
    float32, so the Rust test regenerates the same words."""
    s, out = SEED, []
    for _ in range(calls):
        row = []
        for _ in range(8):
            s ^= (s << 13) & 0xFFFFFFFF
            s ^= s >> 17
            s ^= (s << 5) & 0xFFFFFFFF
            row.append(fb.bits(((s >> 8) - (1 << 23)) / (1 << 25)))
        out.append(row)
    return out


def impulse_words(calls: int) -> list[list[int]]:
    rows = [[0] * 8 for _ in range(calls)]
    rows[0][0] = rows[0][1] = fb.bits(1.0)
    return rows


def fnv(words) -> int:
    """FNV-1a 64 over the 32-bit words, little endian, `-0` read as `+0`."""
    h = FNV_OFFSET
    for w in words:
        w = 0 if w & 0x7FFFFFFF == 0 else w
        for k in range(4):
            h = ((h ^ ((w >> (8 * k)) & 0xFF)) * FNV_PRIME) & M64
    return h


def run_case(image: str, binary: Path, rvb_type: int, amount: int, kind: str) -> dict:
    frames = (impulse_words if kind == "impulse" else noise_words)(CALLS)
    mem0 = rr.real_layout(image, rvb_type, amount)
    send, dry = amount_words(amount)
    mem0.update({rr.RCTX + o: w for o, w in ((0x12, send), (0x13, dry), (0x14, send), (0x15, dry))})
    got = fb.parse_dumps(rr.run_oracle(image, binary, frames, mem0))
    rows = [[got[k][rr.IN_ADDR + j] for j in range(8)] for k in range(CALLS)]
    flat = [w for r in rows for w in r]
    nonzero = [k for k, r in enumerate(rows) if any(w & 0x7FFFFFFF for w in r)]
    first = nonzero[0] if nonzero else 0
    picks = sorted({first, first + 1, first + 2, 1500, 2100, CALLS - 1})
    return {
        "type": rvb_type, "send": send, "dry": dry, "kind": kind, "hash": fnv(flat),
        "nonzero": sum(1 for w in flat if w & 0x7FFFFFFF), "first": first,
        "samples": [(k, [0 if w & 0x7FFFFFFF == 0 else w for w in rows[k]]) for k in picks],
    }  # fmt: skip


def rust(cases: list[dict]) -> str:
    out = [
        "//! Golden vectors of the firmware reverb: oracle output of `0x12417E` on the real instance.",
        "//!",
        "//! GENERATED by `python tools/fx_rvbcore_golden.py` (`sharc-fx` oracle, FX image core 2); derived",
        "//! numbers only: a hash of every output word, the count of non-zero words, the first call with",
        "//! output and some sample calls (8 words each, `-0` as `+0`).",
        "",
        "pub(super) struct Golden {",
        "    pub rvb_type: usize,",
        "    pub send: u32,",
        "    pub dry: u32,",
        "    pub noise: bool,",
        "    pub hash: u64,",
        "    pub nonzero: usize,",
        "    pub first: usize,",
        "    pub samples: &'static [(usize, [u32; 8])],",
        "}",
        "",
        f"pub(super) const CALLS: usize = {CALLS};",
        f"pub(super) const SEED: u32 = {SEED:#x};",
        "",
        f"pub(super) const GOLDEN: [Golden; {len(cases)}] = [",
    ]
    for c in cases:
        out += [
            "    Golden {",
            f"        rvb_type: {c['type']},",
            f"        send: {c['send']:#010x},",
            f"        dry: {c['dry']:#010x},",
            f"        noise: {str(c['kind'] == 'noise').lower()},",
            f"        hash: {c['hash']:#018x},",
            f"        nonzero: {c['nonzero']},",
            f"        first: {c['first']},",
            "        samples: &[",
            *[
                f"            ({k}, [{', '.join(f'{w:#010x}' for w in ws)}]),"
                for k, ws in c["samples"]
            ],
            "        ],",
            "    },",
        ]
    out += ["];", ""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    p.add_argument("image")
    p.add_argument("--bin")
    a = p.parse_args(argv)
    binary = fb.find_binary(a.bin)
    cases = [run_case(a.image, binary, t, amt, kind) for t, amt, kind in CASES]
    sys.stdout.write(rust(cases))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
