    step(0x12403F,w={13:ld(I(6)),12:fmul(r(0),r(5)),9:fsub(r(9),r(13))},d={"i6":mod(6,2)})
    step(0x124042,w={15:ld(I(6)),14:fmul(r(2),r(5)),11:fsub(r(11),r(15))},d={"i6":mod(6,2)})
