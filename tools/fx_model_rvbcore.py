"""Instruction-level model of the FX reverb core `0x123F61` (types 0 and 1, SPRING).

Transliteration of the routine in the style of `tools/fx_pe.py`: one `step` per executed
instruction (`pc` in 16-bit parcels), exact arithmetic with the 40-bit rounding of the oracle. The
steps were produced from the `sharc-visa` listing of the FX Core 2 image; `docs/research/
fx-reverb-leslie.md` s7 has the dataflow. Circular buffers: `Machine.mod` (`B`/`L` registers).

Memory read (`c[n]` = word `I1 + n`): the type words `c[-0x12 .. 0x30]` and the pointer words
`c[39 .. 41] c[43]` (line A), `c[44 .. 46] c[48]` (line B), `c[50] c[32] c[52]` (all-pass buffer),
`c[-13]` and `c[-12]` (loop state and the PM coefficient list); each call reads two frames at
`R0`, `R4` and returns two in `R12`, `R14`. `Machine.trace` compares every instruction with a
`sharc-fx --trace` (`check_core` in `tools/fx_rvbcore_check.py`).
"""

from __future__ import annotations

from fractions import Fraction

import fx_pe
from fx_pe import M32, Machine, fpass, swap, wd

#: VERIFIED (oracle, 60 calls): a float result below the smallest normal number flushes to zero.
TINY = Fraction(1, 2**126)


def _flushed(op):
    return lambda *a: [Fraction(0) if abs(v) < TINY else v for v in op(*a)]


fadd, favg, fmul, fsub = (_flushed(o) for o in (fx_pe.fadd, fx_pe.favg, fx_pe.fmul, fx_pe.fsub))

PC, END = 0x123F61, 0x12417D


def _ops(m: Machine):
    """The short names of the generated steps: `A(k, off)` is `Ik + off`, `I(k)` / `M(k)` read."""
    return (
        m.step, m.r, m.ld, m.ldb, lambda k, o: m.a(f"i{k}", o),
        lambda k: m.ir[f"i{k}"], lambda k: m.ir[f"m{k}"], m.mod, m.x, m.y,
        lambda k, j: (m.ir[f"i{k}"] + m.ir[f"m{j}"]) & M32,
    )  # fmt: skip


# fmt: off
