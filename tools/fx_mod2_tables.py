#!/usr/bin/env python3
# ruff: noqa: E501
"""Data tables of the Mod 2 routines (FX core 2 SRAM), as a CSV and as Rust.

* `ens`: 1025 words at DM `0xC0BD4` (1024 samples and a copy of the first, for the `+1` of a pair read) read by `ENS` (`0x123A7B`, `i6=0xc0bd4`): a 10 bit index
  (`fext` of the LFO word) selects a sample of a waveform (`+-50`, zero crossings at 255, 511, ...).
* `phas`: 258 words at DM `0xE3D81`, two tables of 129 entries (values `0.00038 .. 1.19`) read by
  `PHAS 0` (`0x12379B`) through the pointer word `c[0x1A]` of its instance row (image row of the
  synth / piano unit).

`extract` reads them from the local FX core 2 SRAM image (`tools/ns4_dsp_ldr.py --sram`, never
committed); `docs/research/data/fx-mod2-tables.csv` is the derived list. `rust` writes
`crates/nord-core/src/fx/fw_mod2_tables.rs` from the CSV, `--check` exits 1 when it is stale.

    python tools/fx_mod2_tables.py extract SRAM/core2_sram.bin    # rewrite the CSV
    python tools/fx_mod2_tables.py check SRAM/core2_sram.bin      # CSV equals the local image
    python tools/fx_mod2_tables.py rust [--check]
"""

from __future__ import annotations

import argparse
import csv
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CSV = ROOT / "docs" / "research" / "data" / "fx-mod2-tables.csv"
RUST = ROOT / "crates" / "nord-core" / "src" / "fx" / "fw_mod2_tables.rs"
#: name -> (DM address, number of words)
TABLES = {"ens": (0xC0BD4, 1025), "phas": (0xE3D81, 258)}
HEADER = """//! Data tables of the firmware Mod 2 routines (derived value lists, `fw_ens.rs`, `fw_phas0.rs`).
//!
//! VERIFIED: the words are the DM contents of the FX core 2 SRAM of OS v1.66 (`ENS`: `0xC0BD4`,
//! 1025 words; `PHAS`: `0xE3D81`, 258 words). `python tools/fx_mod2_tables.py check
//! SRAM/core2_sram.bin` compares them with the local firmware, `python tools/fx_mod2_tables.py
//! rust --check` with `docs/research/data/fx-mod2-tables.csv`. The `ENS` table has no closed
//! form (a sampled waveform), the `PHAS` words are decimal literals (`0.000758`, ...).
//! GENERATED by `tools/fx_mod2_tables.py rust`; do not edit.
"""
TESTS = """#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_tables_have_the_documented_shape() {
        assert_eq!(ENS_TABLE.len(), 1025);
        assert_eq!(ENS_TABLE[1024], ENS_TABLE[0], "guard copy");
        assert_eq!((ENS_TABLE[0], ENS_TABLE[255]), (0x410b_3c5b, 0));
        assert_eq!(PHAS_TABLE.len(), 258);
        assert_eq!((PHAS_TABLE[0], PHAS_TABLE[129]), (0x3a46_b484, 0x39c6_b484));
        let f = |k: usize| f32::from_bits(PHAS_TABLE[k]);
        assert!((1..129).all(|k| f(k - 1) < f(k)));
    }
}
"""


def extract(image: bytes) -> dict[str, list[int]]:
    """The tables of a core 2 flat SRAM image (`4 * address` bytes in)."""
    return {
        name: [struct.unpack_from("<I", image, 4 * (addr + k))[0] for k in range(n)]
        for name, (addr, n) in TABLES.items()
    }


def load(path: Path = CSV) -> dict[str, list[int]]:
    """The committed tables."""
    out: dict[str, list[int]] = {name: [] for name in TABLES}
    with path.open(encoding="utf-8") as f:
        for row in csv.DictReader(f):
            out[row["table"]].append(int(row["word"], 16))
    return out


def write_csv(tables: dict[str, list[int]], path: Path = CSV) -> None:
    with path.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["table", "index", "word"])
        for name, words in tables.items():
            for k, word in enumerate(words):
                w.writerow([name, k, f"{word:#010x}"])


def rust(tables: dict[str, list[int]]) -> str:
    out = [HEADER]
    for name, words in tables.items():
        addr = TABLES[name][0]
        out.append(f"/// `{name.upper()}` table, DM `{addr:#x}`, {len(words)} words.")
        out.append(f"pub(super) const {name.upper()}_TABLE: [u32; {len(words)}] = [")
        for i in range(0, len(words), 8):
            out.append("    " + ", ".join(f"{w:#010x}" for w in words[i : i + 8]) + ",")
        out.append("];\n")
    out.append(TESTS)
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("cmd", choices=["extract", "check", "rust"])
    ap.add_argument("image", nargs="?")
    ap.add_argument("--check", action="store_true")
    ns = ap.parse_args(argv)
    if ns.cmd == "rust":
        text = rust(load())
        if ns.check:
            stale = not RUST.exists() or RUST.read_text(encoding="utf-8") != text
            print("stale" if stale else "up to date")
            return 1 if stale else 0
        RUST.write_text(text, encoding="utf-8", newline="\n")
        return 0
    if not ns.image:
        ap.error("image required")
    tables = extract(Path(ns.image).read_bytes())
    if ns.cmd == "extract":
        write_csv(tables)
        return 0
    same = tables == load()
    print("tables equal the local image" if same else "MISMATCH")
    return 0 if same else 1


if __name__ == "__main__":
    sys.exit(main())
