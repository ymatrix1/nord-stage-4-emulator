#!/usr/bin/env python3
"""Golden vectors of the generated Mod 1 models (RM, WAH, A-WAH, PUMP) for the Rust ports.

    python tools/fx_golden_mod1.py > crates/nord-core/src/fx/tests_mod1_golden.rs

Same recipe as `tools/fx_golden_mod2_rest.py` (3 calls of 2 blocks on a seeded scenario of
`tools/fx_model_mod2.py`, the state carried between calls); the structure `Golden` is the one of
`tests_mod2_golden.rs`.
"""

from __future__ import annotations

import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent))
import fx_golden_mod2_rest as g

NAMES = {"rm": "RM", "wah": "WAH", "awah": "AWAH", "pump": "PUMP"}


def main() -> int:
    g.NAMES = NAMES
    print(
        "//! Firmware parity of the generated Mod 1 routines (`0x1239D0` RM, `0x123DD2` WAH,\n"
        "//! `0x123E9B` A-WAH, `0x122D2C` PUMP): golden vectors.\n"
        "//!\n"
        "//! Derived values only (context, input and output words of 3 calls with the state\n"
        "//! carried), generated by `python tools/fx_golden_mod1.py > <this file>` from\n"
        "//! the models that match the `sharc-fx` run of the firmware routines word for word\n"
        "//! (`docs/research/fx-mod-types.md`).\n"
        "\n"
        "pub(super) use super::tests_mod2_golden::Golden;\n"
    )
    for name in NAMES:
        print(g.golden(name))
    names = ", ".join(f"&{n}" for n in NAMES.values())
    print(
        "#[test]\n"
        "fn golden_vectors_have_the_documented_shapes() {\n"
        f"    for v in [{names}] {{\n"
        f"        assert_eq!(v.ctx_in.len(), {g.CTX_N});\n"
        f"        assert_eq!(v.ctx_out.len(), {g.CTX_N});\n"
        f"        assert_eq!(v.frames_in.len(), {4 * g.BLOCKS * g.CALLS});\n"
        f"        assert_eq!(v.frames_out.len(), {4 * g.BLOCKS * g.CALLS});\n"
        "        assert!(v.frames_in != v.frames_out && v.ctx_in != v.ctx_out);\n"
        "    }\n"
        "}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
