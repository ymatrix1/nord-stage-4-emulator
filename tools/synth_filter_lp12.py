#!/usr/bin/env python3
"""Bit-exact model of the Core2 synth filter stage `0x1253BD` (table index 0): the 12 dB low pass.

Listing `0x24A77A..0x24A93A` (ORG core 2). Same prologue as `0x12566E` ([synth_filter_model]) with
the damping table `D` at `DM(0xB0F94)` instead of `B`, and **one** section instead of two:

    cin = A[idx] + (A[idx+1] - A[idx]) fr          table A at DM(0xB0D0F)
    P   = D[idx] + (D[idx+1] - D[idx]) fr          table D at DM(0xB0F94) (this module's CSV)
    N   = 1 / sqrt(1 + R P + R^2),  g = 2 R N,  k = P N
    out = section(cin x)                           the same section as `0x12566E`

Compared with the oracle by `python tools/synth_filter_lp12.py --image SRAM_ORG/core2_sram.bin`
(`docs/research/synth-filter-type-map.md`); the table D CSV is derived words of the image.
"""

from __future__ import annotations

import argparse
import csv
import random
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent))
import struct

import sharc40 as s
import synth_filter_model as f

DATA = Path(__file__).resolve().parents[1] / "docs/research/data"
TABLE_D_ADDR = 0xB0F94


def f2u(x: float) -> int:
    """float32 bits of a Python float."""
    return struct.unpack("<I", struct.pack("<f", x))[0]


TABLE_LEN = 129
STAGE = 0x1253BD


def read_tables() -> tuple[list[int], list[int]]:
    """Tables `(A, D)` as float32 words (A from the filter-table CSV, D from its own CSV)."""
    a = []
    with (DATA / "synth-filter-tables.csv").open() as fh:
        for row in csv.DictReader(fh):
            a.append(f2u(float(row["A_0xB0D0F"])))
    d = []
    with (DATA / "synth-filter-table-d.csv").open() as fh:
        for row in csv.DictReader(fh):
            d.append(int(row["word"], 16))
    return a, d


def process(lane: f.Lane, coefs: tuple[int, int, int], xs: list[int], limit_word=0x3F800000):
    """One lane, one section: the output words of the sample words `xs`."""
    cin, g, k = (s.ld(w) for w in coefs)
    limit = s.ld(limit_word)
    out = []
    for xw in xs:
        u = s.fmul(s.ld(xw), cin)
        y, lane.a1, lane.b1, lane.c1 = f.section(u, lane.a1, lane.b1, lane.c1, g, k, limit)
        out.append(s.st(y))
    return out


RUST_HEAD = """//! Damping table `D` of the 12 dB low pass `0x1253BD` (derived values only).
//!
//! Generated by `python tools/synth_filter_lp12.py --rust-table-d` from
//! `docs/research/data/synth-filter-table-d.csv` (float32 words of `DM(0xB0F94 ..)` of the ORG
//! core 2 image, 129 entries). VERIFIED: the model that uses it equals the oracle word for word
//! (`docs/research/synth-filter-type-map.md`); test `table_equals_the_research_csv`.

"""
RUST_TAIL = """
#[cfg(test)]
mod tests {
    use super::*;

    const CSV: &str = include_str!(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../docs/research/data/synth-filter-table-d.csv"
    ));

    #[test]
    fn table_equals_the_research_csv() {
        let words: Vec<u32> = CSV
            .lines()
            .skip(1)
            .map(|l| {
                let w = l.split(',').nth(1).unwrap().trim_start_matches("0x");
                u32::from_str_radix(w, 16).unwrap()
            })
            .collect();
        assert_eq!(words, TABLE_D_BITS);
        assert_eq!(f32::from_bits(TABLE_D_BITS[0]), 2.0);
    }
}
"""


def rust_table_d() -> str:
    """The Rust table file `synth/fw_filter_table_d.rs` generated from the CSV."""
    d = read_tables()[1]
    rows = "".join(
        "    " + ", ".join(f"{w:#010x}" for w in d[i : i + 8]) + ",\n" for i in range(0, len(d), 8)
    )
    return RUST_HEAD + f"pub(super) const TABLE_D_BITS: [u32; {len(d)}] = [\n{rows}];\n" + RUST_TAIL


def dump_table_d(image: str) -> str:  # pragma: no cover - needs the firmware image
    """CSV text of table D from the core 2 image (`DM(addr)` = bytes `4 addr`)."""
    data = Path(image).read_bytes()
    rows = ["index,word"]
    for i in range(TABLE_LEN):
        w = int.from_bytes(data[4 * (TABLE_D_ADDR + i) : 4 * (TABLE_D_ADDR + i) + 4], "little")
        rows.append(f"{i},{w:#010x}")
    return "\n".join(rows) + "\n"


def compare(sharc_org: str, image: str, trials: int):  # pragma: no cover - needs the firmware
    """`(equal, total)` output words of the model against the oracle."""
    import synth_stage_oracle as o

    a, d = read_tables()
    patched = Path(image).with_name("core2_patched.bin")
    patched.write_bytes(o.patch_controls(Path(image).read_bytes()))
    equal = total = 0
    for seed in range(1, trials + 1):
        rng = random.Random(seed)
        r_word = o.f2u(rng.uniform(0.02, 0.7))
        w28 = (rng.randrange(0, 126) << 24) | rng.randrange(0, 1 << 24)
        xs = [rng.uniform(-1, 1) for _ in range(64)]
        zero = (0, 0)
        frame = {-30: (r_word, r_word), -28: (w28, w28), -10: zero, -8: zero, -6: zero}
        got = o.run_stage(sharc_org, str(patched), STAGE, frame, xs)["x"]
        coefs = f.coefficients(w28, r_word, a, d)
        want = process(f.Lane(), coefs, [o.f2u(x) for x in xs])
        for w, g in zip(want, got, strict=True):
            total += 1
            equal += w == o.f2u(g)
    return equal, total


def main(argv: list[str] | None = None) -> int:  # pragma: no cover - thin CLI
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--image")
    ap.add_argument("--sharc-org", default="target/release/sharc-org")
    ap.add_argument("--trials", type=int, default=20)
    ap.add_argument("--dump-d", action="store_true", help="print table D as CSV and exit")
    ap.add_argument("--rust-table-d", action="store_true", help="print the Rust table file")
    ns = ap.parse_args(argv)
    if ns.rust_table_d:
        sys.stdout.write(rust_table_d())
        return 0
    if ns.image is None:
        ap.error("--image is required")
    if ns.dump_d:
        sys.stdout.write(dump_table_d(ns.image))
        return 0
    equal, total = compare(ns.sharc_org, ns.image, ns.trials)
    print(f"{equal} of {total} output words equal")
    return 0 if equal == total else 1


if __name__ == "__main__":
    sys.exit(main())
