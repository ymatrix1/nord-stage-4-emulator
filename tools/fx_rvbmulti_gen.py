#!/usr/bin/env python3
"""Generate `tools/fx_model_rvbmulti.py` from an ADI listing of the multi-tap reverb.

The module `0xC02BB44C` (reverb types 2..11) runs the wrapper `0x120FDB` (three fs/4 biquads, the
packed multi-tap core, three more biquads at PM `0x9437F`, the dry / wet mix) and the packed core
`0x120D8A` (FPACK / FUNPACK / FEXT / FDEP on 16:16 line words, one `do` loop of 7 passes). Both are
straight-line SIMD code. This tool reuses the listing parser of `tools/fx_leslie_gen.py` (one
`step(...)` per instruction, see `tools/fx_pe.py`) and adds the forms the Leslie code lacks
(`FPACK`, `FUNPACK`, `BTGL`, `x OR FDEP y`, `IF NOT SZ`). It emits instruction semantics only.

    python tools/adi_dis.py SRAM/core2_sram.bin 0x240000 0x242800 > fx.txt   # 0 = pc 0x120000
    python tools/fx_rvbmulti_gen.py fx.txt > tools/fx_model_rvbmulti.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent))
import fx_leslie_gen as lg

lg.BASE = 0x120000
#: VERIFIED (listing `0x120D8A .. 0x120F7B` and `0x120FDB .. 0x1211C0`): routine ranges (pc offset);
#: the core's `rts (db)` at `0x120F78` has two delay slots, `0x120F7D` is padding.
ROUTINES = {"core": (0xD8A, 0xF7B), "wrapper": (0xFDB, 0x11C0)}

_orig_compute = lg.compute


def compute(rhs: str, dst: str, stp: lg.Step) -> bool:
    """`lg.compute` plus the packed-float and bit forms of the multi-tap core."""
    md = lg.DREG.match(dst)
    if md:
        n = int(md.group(1))
        m = re.match(r"^fpack (\w+)$", rhs)
        if m:
            stp.w[n] = f"fpack_p({lg.read_reg(m.group(1))})"
            return True
        m = re.match(r"^funpack (\w+)$", rhs)
        if m:
            stp.w[n] = f"funpack_p({lg.read_reg(m.group(1))})"
            return True
        m = re.match(r"^btgl (\w+) by (\d+)$", rhs)
        if m:
            stp.w[n] = f"ibtgl({lg.read_reg(m.group(1))},imm({int(m.group(2))}))"
            stp.fl = f"flags_val({stp.w[n]})"  # SZ of the shifter result
            return True
        m = re.match(r"^(\w+) or fdep (\w+) by (0x[0-9a-f]+):(0x[0-9a-f]+)$", rhs)
        if m:
            old, src = lg.read_reg(m.group(1)), lg.read_reg(m.group(2))
            stp.w[n] = f"fdep_or({old},{src},imm({lg.num(m.group(3))}),imm({lg.num(m.group(4))}))"
            return True
    return _orig_compute(rhs, dst, stp)


lg.compute = compute


def gen(lst: dict[int, tuple[int, str]]) -> list[str]:
    """Source lines of the generated model module."""
    out = [
        "# ruff: noqa: E741, F403, F405, E501",
        '"""Instruction-level model of the multi-tap reverb: core `0x120D8A`, wrapper `0x120FDB`.',
        "",
        "Generated by `tools/fx_rvbmulti_gen.py` from an ADI listing (instruction semantics only).",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from fx_rvbmulti_ops import *  # noqa: F403",
        "",
    ]
    for name, (a, b) in ROUTINES.items():
        body = lg.gen_routine(dict(lst), a, b, name)
        out += [ln.replace("m.call()", "core(m)") for ln in body]
        out.append("")
    return out


def main(argv: list[str] | None = None) -> int:
    lst = lg.parse_listing(Path((argv or sys.argv[1:])[0]))
    # `if not sz` is the complement of the shifter zero flag: the model keeps one flag pair.
    lst = {k: (n, t.replace("if not sz ", "if ne ")) for k, (n, t) in lst.items()}
    sys.stdout.write("\n".join(gen(lst)) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
