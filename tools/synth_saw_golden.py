#!/usr/bin/env python3
"""Golden grid of the firmware saw for the Rust port (`crates/nord-core/src/synth/hw_saw.rs`).

    python tools/synth_saw_golden.py > crates/nord-core/src/synth/tests_hw_saw_golden.rs

512 phase/increment pairs: the grid of `synth_saw_model.check` (8 increments x 64 phases
`k 2^26 + 12345`), each with one of the four block samples `j = 1 + (index mod 4)`. Phases and
increments are rounded to float32 first and the expected value is the closed form of
`synth_saw_model.saw_sample` evaluated on those float32 inputs, so the Rust float32 arithmetic is
compared with the model on identical inputs. Only derived values appear (the model is checked
against the SHARC oracle in `synth_saw_model.py check`).
"""

from __future__ import annotations

import struct
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent))
import synth_saw_model as m

INCREMENTS = (1 / 512, 1 / 64, 0.09, 0.11, 0.125, 0.15, 0.2, 0.25)
PHASES = 64


def f32(x: float) -> float:
    """`x` rounded to float32."""
    return struct.unpack("<f", struct.pack("<f", x))[0]


def bits(x: float) -> int:
    """Float32 bit pattern of `x`."""
    return struct.unpack("<I", struct.pack("<f", x))[0]


def grid() -> list[tuple[float, float, float]]:
    """`(phase, inc, expected)` of the 512 grid points, all float32 values."""
    rows = []
    for inc_cycles in INCREMENTS:
        inc_q = int(inc_cycles * 2**32)
        inc = f32(inc_q / 2**32)
        for k in range(PHASES):
            phase_q = (k * (1 << 26) + 12345) & 0xFFFFFFFF
            j = 1 + len(rows) % 4
            p = f32(((phase_q / 2**32) + j * (inc_q / 2**32)) % 1.0)
            assert 0.0 <= p < 1.0
            rows.append((p, inc, f32(m.saw_sample(p, inc))))
    return rows


def words_rust(name: str, words: list[int]) -> str:
    """A `pub(super) const NAME: [u32; N]` with eight hex words per line."""
    body = "".join(
        "    " + ", ".join(f"{w:#010x}" for w in words[i : i + 8]) + ",\n"
        for i in range(0, len(words), 8)
    )
    return f"pub(super) const {name}: [u32; {len(words)}] = [\n{body}];\n"


def rust() -> str:
    """The whole Rust golden file."""
    rows = grid()
    head = (
        "//! Firmware parity of the synth saw (`hw_saw.rs`): 512-point golden grid.\n"
        "//!\n"
        "//! Derived values only (float32 phase, increment and expected sample), generated by\n"
        "//! `python tools/synth_saw_golden.py > <this file>` from the closed form that\n"
        "//! matches the SHARC oracle run of the helper `0x12501F` within 5.9e-8\n"
        "//! (`docs/research/synth-voice-control.md` section 5).\n\n"
        "use super::hw_saw::firmware_saw;\n\n"
    )
    body = (
        words_rust("HW_SAW_PHASE", [bits(r[0]) for r in rows])
        + words_rust("HW_SAW_INC", [bits(r[1]) for r in rows])
        + words_rust("HW_SAW_OUT", [bits(r[2]) for r in rows])
    )
    tests = """
#[test]
fn rust_saw_matches_the_golden_grid_within_float32_rounding() {
    let mut worst = 0.0f32;
    for ((&p, &inc), &want) in HW_SAW_PHASE.iter().zip(&HW_SAW_INC).zip(&HW_SAW_OUT) {
        let got = firmware_saw(f32::from_bits(p), f32::from_bits(inc));
        worst = worst.max((got - f32::from_bits(want)).abs());
    }
    assert!(worst < 2e-6, "worst deviation {worst}");
}

#[test]
fn golden_grid_has_the_documented_shape() {
    assert_eq!(HW_SAW_PHASE.len(), 512);
    assert_eq!(HW_SAW_INC.len(), HW_SAW_PHASE.len());
    assert_eq!(HW_SAW_OUT.len(), HW_SAW_PHASE.len());
    // the two highest increments are above the fade end (0.2304) or inside it
    assert!(HW_SAW_OUT[448..].iter().any(|&w| f32::from_bits(w) == 0.0));
}
"""
    return head + body + tests


def main(argv: list[str] | None = None) -> int:  # pragma: no cover - thin CLI
    sys.stdout.reconfigure(newline="\n")  # LF on Windows too
    print(rust(), end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
