#!/usr/bin/env python3
# ruff: noqa: E501
"""Instance rows, type words and parameter laws of the wired Mod 2 types, as Rust.

The wired types read their words from three derived sources (nothing here is firmware code):

* **rows**: the non-zero words of the instance row of the synth / piano unit in the static FX
  image (core 1 flat SRAM, `tools/ns4_dsp_ldr.py --sram`), `docs/research/data/fx-mod2-rows.csv`;
* **type words**: what the ARM writes at the type switch (`fx-type-words.csv`, piano rows);
* **laws**: the 11 samples of every `kFx2Amt` / `kFx2Rate` write (`fx-param-fits.csv`, piano rows).

    python tools/fx_mod2_laws.py rows SRAM/core1_sram.bin   # rewrite fx-mod2-rows.csv
    python tools/fx_mod2_laws.py check SRAM/core1_sram.bin  # the CSV equals the local image
    python tools/fx_mod2_laws.py rust [--check]             # fw_mod2_data.rs from the three CSVs
"""

from __future__ import annotations

import argparse
import csv
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "docs" / "research" / "data"
ROWS_CSV = DATA / "fx-mod2-rows.csv"
RUST = ROOT / "crates" / "nord-core" / "src" / "fx" / "fw_mod2_data.rs"
#: `I1` of the instance row of the piano / synth unit (`fx-type-words.csv`: first word + offset).
BASES = {
    "flang": 0xB024C,
    "phas0": 0xB0348,
    "phas1": 0xB0432,
    "ens": 0xC129E,
    "spin": 0xC1174,
}
#: `kFx2Type` -> routine name
TYPES = {0: "phas0", 1: "phas1", 2: "flang", 3: "flang", 8: "ens", 9: "ens", 10: "spin", 11: "spin"}
LO, HI = -32, 0x2A
SAMPLES = [0, 1, 2, 15, 31, 47, 63, 79, 95, 111, 127]


def row_words(image: bytes) -> list[tuple[str, int, int]]:
    out = []
    for name, base in BASES.items():
        for off in range(LO, HI + 1):
            w = struct.unpack_from("<I", image, 4 * (base + off))[0]
            if w:
                out.append((name, off, w))
    return out


def read_rows() -> list[tuple[str, int, int]]:
    with ROWS_CSV.open(encoding="utf-8") as f:
        return [(r["name"], int(r["offset"]), int(r["word"], 16)) for r in csv.DictReader(f)]


def write_rows(rows: list[tuple[str, int, int]]) -> None:
    with ROWS_CSV.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["name", "offset", "word"])
        for name, off, word in rows:
            w.writerow([name, off, f"{word:#010x}"])


def type_words() -> dict[int, dict[int, int]]:
    """Piano rows of `fx-type-words.csv`: type -> {ctx offset: first word}."""
    out: dict[int, dict[int, int]] = {t: {} for t in TYPES}
    with (DATA / "fx-type-words.csv").open(encoding="utf-8") as f:
        for r in csv.DictReader(f):
            t = int(r["type"])
            if r["slot"] == "Fx2" and t in TYPES and "piano" in r["kinds"]:
                out[t].setdefault(int(r["ctx"]), int(r["word"], 16))
    return out


def laws() -> dict[int, dict[str, dict[int, tuple[bool, list[int]]]]]:
    """type -> {"Amt" | "Rate": {ctx offset: (float, 11 sample words)}} from piano rows."""
    out: dict[int, dict[str, dict[int, tuple[bool, list[int]]]]] = {
        t: {"Amt": {}, "Rate": {}} for t in TYPES
    }
    with (DATA / "fx-param-fits.csv").open(encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if r["slot"] != "Fx2" or not r["type"] or int(r["type"]) not in TYPES:
                continue
            t = int(r["type"])
            if "piano" not in r["kinds"]:
                continue
            kind = "Amt" if r["id"].endswith("kFx2Amt") else "Rate"
            pts = dict(s.split(":") for s in r["samples"].split(";"))
            words = [int(pts[str(v)], 16) for v in SAMPLES]
            out[t][kind].setdefault(int(r["ctx"]), (r["float"] == "1", words))
    return out


def _pairs(d: dict[int, int]) -> str:
    return "&[" + ", ".join(f"({o}, {w:#x})" for o, w in sorted(d.items())) + "]"


def _law_list(d: dict[int, tuple[bool, list[int]]]) -> str:
    rows = []
    for off, (flt, words) in sorted(d.items()):
        body = ", ".join(f"{w:#x}" for w in words)
        rows.append(f"    Law {{ off: {off}, float: {str(flt).lower()}, words: [{body}] }},")
    return "&[\n" + "\n".join(rows) + "\n]"


def rust() -> str:
    rows = read_rows()
    tw, lw = type_words(), laws()
    out = [
        "//! Instance rows, type words and parameter laws of the wired Mod 2 types (derived values).",
        "//!",
        "//! GENERATED by `python tools/fx_mod2_laws.py rust` from `docs/research/data/fx-mod2-rows.csv`,",
        "//! `fx-type-words.csv` and `fx-param-fits.csv` (piano rows); do not edit. VERIFIED at the 11",
        "//! captured values of every law (`SAMPLES`), EMPIRICAL between them (linear interpolation);",
        "//! the words the ARM writes per layer kind are the piano ones for every layer (ASSUMED).",
        "// ENS (types 8, 9) and PHAS 1 (type 1) are listed for the follow-up; no stage uses them yet.",
        "#![allow(dead_code)]",
        "",
        "/// Values of `kFx2Amt` / `kFx2Rate` at which the ARM writes were captured.",
        f"pub(super) const SAMPLES: [u32; 11] = {SAMPLES};",
        "",
        "/// One context word as a function of a 7 bit parameter: 11 samples (a float word or an integer).",
        "pub(super) struct Law {",
        "    pub(super) off: i32,",
        "    pub(super) float: bool,",
        "    pub(super) words: [u32; 11],",
        "}",
        "",
    ]
    for name in BASES:
        out.append(
            f"/// Non-zero words of the `{name.upper()}` instance row `c[off]` (static FX image)."
        )
        out.append(
            f"pub(super) const ROW_{name.upper()}: &[(i32, u32)] = "
            + _pairs({o: w for n, o, w in rows if n == name})
            + ";"
        )
    out.append("")
    for t, name in TYPES.items():
        out.append(f"/// Words the ARM writes at the switch to `kFx2Type` {t} (piano row).")
        out.append(f"pub(super) const WORDS_{t}: &[(i32, u32)] = " + _pairs(tw[t]) + ";")
    out.append("")
    for t, name in TYPES.items():
        for kind in ("Amt", "Rate"):
            out.append(f"/// `kFx2{kind}` laws of `kFx2Type` {t} (`{name.upper()}`).")
            out.append(
                f"pub(super) const {kind.upper()}_{t}: &[Law] = " + _law_list(lw[t][kind]) + ";"
            )
    text = "\n".join(out) + "\n"
    # rows and laws keep one line per entry (`cargo fmt` would spread every word)
    return (
        text.replace("pub(super) const ROW_", "#[rustfmt::skip]\npub(super) const ROW_")
        .replace("pub(super) const WORDS_", "#[rustfmt::skip]\npub(super) const WORDS_")
        .replace("pub(super) const AMT_", "#[rustfmt::skip]\npub(super) const AMT_")
        .replace("pub(super) const RATE_", "#[rustfmt::skip]\npub(super) const RATE_")
    )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("cmd", choices=["rows", "check", "rust"])
    ap.add_argument("image", nargs="?")
    ap.add_argument("--check", action="store_true")
    ns = ap.parse_args(argv)
    if ns.cmd == "rust":
        text = rust()
        if ns.check:
            stale = not RUST.exists() or RUST.read_text(encoding="utf-8") != text
            print("stale" if stale else "up to date")
            return 1 if stale else 0
        RUST.write_text(text, encoding="utf-8", newline="\n")
        return 0
    if not ns.image:
        ap.error("image required")
    rows = row_words(Path(ns.image).read_bytes())
    if ns.cmd == "rows":
        write_rows(rows)
        return 0
    same = rows == read_rows()
    print("rows equal the local image" if same else "MISMATCH")
    return 0 if same else 1


if __name__ == "__main__":
    sys.exit(main())
