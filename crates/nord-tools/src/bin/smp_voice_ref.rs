//! `smp_voice_ref FILE.npno PREFIX [--stroke N] [--step R] [--frames N] [--gain G] [--hist-off N]
//!  [--phase0 W] [--base-words K] [--compare]`
//!
//! Oracle test of the SMP compressed-voice loop (`docs/research/smp-voice.md`).
//! Without `--compare` it writes `PREFIX.scn`, a `sharc-ref` scenario that loads page 0 of one
//! stroke of a local `.npno` into the stream ring (refilled by `poke` as the read position
//! advances, like the external-port DMA), builds one voice record per channel, and runs one audio
//! interrupt per output frame. With `--compare` it reads the oracle dump `PREFIX.csv`, replays the
//! same voices with `nord_core::piano::smp_voice` and prints the agreement, plus the comparison
//! with the engine path (`SmpKernel::interpolate` on the decoded stroke). Inputs stay local.
use nord_core::cbin::piano_sample::{decode_npno_stroke, NpnoInstrument, NpnoStroke};
use nord_core::piano::q31_kernel::SmpKernel;
use nord_core::piano::smp_page::{
    fnv64, page_voices, play_page, synthetic_page, Frame, NpnoPage, PlayConfig, NPNO_PAGE_BYTES,
};
use nord_core::piano::smp_unpack::FIXED_LPC_COEFFS;
use nord_core::piano::smp_voice::{mul_ssf, HIST_WORDS, RING_WORDS};
use nord_tools::csv_cols::{join, read_csv};
use std::fmt::Write as _;

/// Free DM area of the SMP image (zero-filled, not touched by the audio ISR).
const RING: u32 = 0x9B200;
const COEF: u32 = 0x9B320;
const BUS: u32 = 0x9B330;
/// Record pointer `I3` of voice `v` (fields span -32..+4).
fn rec(v: usize) -> u32 {
    0x9B420 + 0x40 * v as u32
}
fn hist_addr(v: usize) -> u32 {
    0x9B300 + 0x10 * v as u32
}

struct Cfg {
    stroke: Option<usize>,
    frames: usize,
    /// `--base-words` starts the read inside the stream (the engine comparison is skipped then).
    play: PlayConfig,
}

fn parse(args: &[String]) -> Result<Cfg, String> {
    let get = |k: &str| args.windows(2).find(|w| w[0] == k).map(|w| w[1].clone());
    let num = |k: &str, d: f64| {
        get(k).map_or(Ok(d), |v| v.parse::<f64>().map_err(|_| format!("bad {k}")))
    };
    Ok(Cfg {
        stroke: get("--stroke")
            .map(|v| v.parse().map_err(|_| "bad --stroke"))
            .transpose()?,
        frames: num("--frames", 1200.0)? as usize,
        play: PlayConfig {
            step: num("--step", 0.5)?,
            gain: num("--gain", f64::from(i32::MAX))? as i32,
            hist_off: num("--hist-off", 0.0)? as u32,
            phase0: num("--phase0", 0.0)? as u32,
            base_words: num("--base-words", 0.0)? as u32,
        },
    })
}

fn load_page(s: &NpnoStroke, bytes: &[u8]) -> Option<NpnoPage> {
    let n = NPNO_PAGE_BYTES * usize::from(s.channels);
    NpnoPage::parse(bytes.get(s.data_offset..s.data_offset + n)?)
}

/// First usable stroke whose page 0 has a moderate width, or the one given by `--stroke`.
fn pick(inst: &NpnoInstrument, bytes: &[u8], want: Option<usize>) -> Result<usize, String> {
    let ok = |s: &NpnoStroke, wide: bool| {
        s.stroke_kind == 0
            && load_page(s, bytes)
                .is_some_and(|p| wide || ((6..=9).contains(&p.nbits) && p.order >= 2))
    };
    match want {
        Some(i) => inst
            .strokes
            .get(i)
            .filter(|s| ok(s, true))
            .map(|_| i)
            .ok_or("stroke unusable".into()),
        None => inst
            .strokes
            .iter()
            .position(|s| ok(s, false))
            .ok_or("no suitable stroke".into()),
    }
}

fn model(page: &NpnoPage, h0: &[[i32; 4]], c: &Cfg) -> Vec<Frame> {
    play_page(page, h0, &c.play, c.frames)
}

fn scenario(page: &NpnoPage, h0: &[[i32; 4]], c: &Cfg, name: &str) -> String {
    let frames = model(page, h0, c);
    let vs = page_voices(page, h0, &c.play);
    let step = (c.play.step * 4_294_967_296.0).round() as u64;
    let mut s = String::new();
    let _ = writeln!(
        s,
        "# generated by smp_voice_ref ({name}); see docs/research/smp-voice.md"
    );
    let _ = writeln!(
        s,
        "meta rate 48000\nwarmup 0x1c11e0 100000 flag12=1\npoke 0x5201 0x40\nfifo 0x92196\nirq 13"
    );
    let mut set = |a: u32, v: u32| {
        let _ = writeln!(s, "poke 0x{a:X} 0x{v:X}");
    };
    for (i, w) in page.words.iter().take(RING_WORDS).enumerate() {
        set(RING + i as u32, *w);
    }
    for (i, k) in FIXED_LPC_COEFFS[usize::from(page.order)].iter().enumerate() {
        set(COEF + i as u32, *k as u32);
    }
    for (n, v) in vs.iter().enumerate() {
        let f = |off: i32| rec(n).wrapping_add_signed(off);
        for (off, val) in [
            (-32, (step >> 32) as u32),
            (-31, step as u32),
            (-30, 0),
            (-29, v.phase),
            (-28, v.stride),
            (-27, v.base),
            (-26, RING),
            (-25, hist_addr(n)),
            (-24, v.hist_off),
            (-19, v.width),
            (-18, BUS),
            (-17, COEF),
            (0, v.gain[0] as u32),
            (1, v.gain[1] as u32),
        ] {
            set(f(off), val);
        }
        for (i, h) in v.hist.iter().enumerate() {
            set(hist_addr(n) + i as u32, *h as u32);
        }
        set(0x92534 + n as u32, rec(n));
    }
    set(0x9268B, vs.len() as u32);
    set(0x9268A, 0);
    for f in &frames {
        for (slot, w) in &f.refill {
            let _ = writeln!(s, "poke 0x{:X} 0x{w:X}", RING + *slot as u32);
        }
        let _ = writeln!(s, "poke 0x{BUS:X} 0\npoke 0x{:X} 0\nirq 17", BUS + 1);
        let r0 = |off: i32| rec(0).wrapping_add_signed(off);
        let mut caps = vec![("bus", BUS, 2), ("cnt", r0(-30), 1), ("pha", r0(-29), 1)];
        for n in 0..vs.len() {
            caps.push(("lst", rec(n) + 4, 1));
            caps.push(("hst", hist_addr(n), HIST_WORDS));
        }
        for (n, a, cnt) in caps {
            for part in ["lo", "hi"] {
                let _ = writeln!(s, "capture {n}_{part} 0x{a:X} {cnt} part={part}");
            }
        }
    }
    s
}

fn stat(name: &str, a: &[f64], r: &[f64]) {
    let (mut exact, mut max_abs, mut se, mut sr) = (0, 0f64, 0f64, 0f64);
    for (x, y) in a.iter().zip(r) {
        exact += usize::from(x == y);
        max_abs = max_abs.max((x - y).abs());
        se += (x - y).powi(2);
        sr += y * y;
    }
    let snr = if se == 0.0 {
        f64::INFINITY
    } else {
        10.0 * (sr / se).log10()
    };
    let n = a.len().min(r.len());
    println!("{name:<38} {exact:>6}/{n:<6} exact  max abs err {max_abs:<12.6e} SNR {snr:.1} dB");
}

fn compare(
    engine: Option<(&NpnoInstrument, &[u8], usize)>,
    page: &NpnoPage,
    h0: &[[i32; 4]],
    c: &Cfg,
    prefix: &str,
) -> Result<(), String> {
    let cols = read_csv(&format!("{prefix}.csv"))?;
    let rows = model(page, h0, c);
    let f = |x: i32| f64::from(x);
    println!(
        "{} channel(s), width {}, order {}, {} residuals/channel on page 0, step {}, {} frames, gain 0x{:X}",
        page.channels, page.nbits, page.order, page.frames(), c.play.step, c.frames, c.play.gain
    );
    let to_i32 = |v: &[f64]| v.iter().map(|&x| x as i32).collect::<Vec<_>>();
    let pairs: Vec<(&str, Vec<f64>, Vec<f64>)> = vec![
        (
            "counter (record -30)",
            join(&cols, "cnt")?,
            rows.iter().map(|r| f(r.counter as i32)).collect(),
        ),
        (
            "phase (record -29)",
            join(&cols, "pha")?,
            rows.iter().map(|r| f(r.phase as i32)).collect(),
        ),
        (
            "history rings (decoded samples)",
            join(&cols, "hst")?,
            rows.iter()
                .flat_map(|r| r.hist.iter().map(|&x| f(x)))
                .collect(),
        ),
        (
            "interpolated << 17 (record +4)",
            join(&cols, "lst")?,
            rows.iter()
                .flat_map(|r| r.last.iter().map(|&x| f(x)))
                .collect(),
        ),
        (
            "bus L,R vs integer model",
            join(&cols, "bus")?,
            rows.iter()
                .flat_map(|r| r.bus.iter().map(|&x| f(x)))
                .collect(),
        ),
    ];
    for (name, a, r) in &pairs {
        stat(name, a, r);
    }
    println!(
        "bus fingerprint: oracle {:016x}, model {:016x}",
        fnv64(&to_i32(&pairs[4].1)),
        fnv64(&to_i32(&pairs[4].2))
    );
    let Some((inst, bytes, idx)) = engine else {
        return Ok(());
    };
    if c.play.base_words != 0 {
        println!(
            "(engine comparison skipped: --base-words moves the read position inside the stream)"
        );
        return Ok(());
    }
    // Engine path: decoded stroke, f32 kernel, read position counter - 4 + phase / 256.
    println!("engine stroke {idx}");
    let (pl, pr) = decode_npno_stroke(&inst.strokes[idx], bytes)?;
    let bus = &pairs[4].1;
    let k = SmpKernel::shared();
    let g = f64::from(c.play.gain) / 2147483648.0;
    let chans: Vec<&Vec<f32>> = if let Some(r) = &pr {
        vec![&pl, r]
    } else {
        vec![&pl]
    };
    for (ch, pcm) in chans.iter().enumerate() {
        let (mut got, mut want, mut got_q, mut want_q) =
            (Vec::new(), Vec::new(), Vec::new(), Vec::new());
        let (mut got_h, mut want_h) = (Vec::new(), Vec::new());
        for (i, r) in rows.iter().enumerate() {
            if r.calls[0].counter < 6 {
                continue; // DSP history starts at zero here, the engine repeats the edge sample
            }
            let pos = f64::from(r.calls[0].counter) - 4.0 + r.calls[0].phase_index as f64 / 256.0;
            let e = f64::from(k.interpolate(pcm, pos).ok_or("engine out of range")?);
            let b = bus[2 * i + if page.channels == 1 { 0 } else { ch }];
            // bus / 2^30 / gain is the engine amplitude (sample 8191 -> 0.5 of Q31 full scale)
            got.push(b / 1_073_741_824.0 / g);
            want.push(e);
            got_q.push(b);
            want_q.push((e * 1_073_741_824.0 * g).round());
            // the same with the integer MAC of the DSP (`interpolate_hw`) and its output chain
            let eh = k.interpolate_hw(pcm, pos).ok_or("engine out of range")?;
            let y = ((eh * 8192.0).round() as i32) << 17;
            got_h.push(b);
            want_h.push(f64::from(mul_ssf(y, c.play.gain)));
        }
        let tag = ["L", "R"][ch];
        stat(
            &format!("bus {tag} vs engine f32 (counter >= 6)"),
            &got,
            &want,
        );
        let lsb = got
            .iter()
            .zip(&want)
            .map(|(a, b)| (a - b).abs())
            .fold(0f64, f64::max)
            * 8192.0;
        println!("  largest difference to the engine: {lsb:.3} LSB of the 1/8192 sample scale");
        stat(
            &format!("bus {tag} raw vs round(engine * 2^30 * g)"),
            &got_q,
            &want_q,
        );
        stat(
            &format!("bus {tag} vs engine interpolate_hw"),
            &got_h,
            &want_h,
        );
    }
    Ok(())
}

fn run(args: &[String]) -> Result<(), String> {
    let [file, prefix, ..] = args else {
        return Err("usage: smp_voice_ref FILE.npno PREFIX [--stroke N] [--step R] [--frames N] [--gain G] [--compare]".into());
    };
    let c = parse(args)?;
    let mut src = None;
    let (page, h0) = if let Some(spec) = file.strip_prefix("synthetic") {
        // synthetic[:ORDER:NBITS:CHANNELS], default order 1, 6 bits, stereo
        let v: Vec<usize> = spec
            .split(':')
            .skip(1)
            .filter_map(|t| t.parse().ok())
            .collect();
        let (o, w, ch) = (
            v.first().copied().unwrap_or(1),
            v.get(1).copied().unwrap_or(6),
            v.get(2).copied().unwrap_or(2),
        );
        (synthetic_page(o as u8, w as u32, ch), vec![[0; 4]; ch])
    } else {
        let bytes = std::fs::read(file).map_err(|e| format!("{file}: {e}"))?;
        let inst = NpnoInstrument::parse(&bytes)?;
        let idx = pick(&inst, &bytes, c.stroke)?;
        let st = &inst.strokes[idx];
        let page = load_page(st, &bytes).ok_or("bad page")?;
        let h0 = [st.init_left.map(i32::from), st.init_right.map(i32::from)];
        let h0 = h0[..page.channels].to_vec();
        src = Some((inst, bytes, idx));
        (page, h0)
    };
    if args.iter().any(|a| a == "--compare") {
        let engine = src.as_ref().map(|(i, b, x)| (i, b.as_slice(), *x));
        return compare(engine, &page, &h0, &c, prefix);
    }
    std::fs::write(format!("{prefix}.scn"), scenario(&page, &h0, &c, file))
        .map_err(|e| e.to_string())?;
    println!(
        "{} channel(s), width {}, order {}, history {h0:?}; wrote {prefix}.scn",
        page.channels, page.nbits, page.order
    );
    Ok(())
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if let Err(e) = run(&args) {
        eprintln!("{e}");
        std::process::exit(1);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn voice_addresses_step_by_their_record_strides() {
        assert_eq!(rec(0), 0x9B420);
        assert_eq!(rec(2) - rec(1), 0x40);
        assert_eq!(hist_addr(0), 0x9B300);
        assert_eq!(hist_addr(3) - hist_addr(2), 0x10);
    }

    #[test]
    fn parse_applies_defaults_and_overrides() {
        let none: Vec<String> = Vec::new();
        let d = parse(&none).unwrap();
        assert_eq!((d.stroke, d.frames), (None, 1200));
        assert_eq!(d.play.step, 0.5);
        let a: Vec<String> = ["--stroke", "3", "--frames", "10", "--step", "1.5"]
            .iter()
            .map(|s| s.to_string())
            .collect();
        let c = parse(&a).unwrap();
        assert_eq!((c.stroke, c.frames, c.play.step), (Some(3), 10, 1.5));
        let bad: Vec<String> = vec!["--frames".into(), "x".into()];
        assert!(parse(&bad).is_err());
    }
}
