#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_has_the_documented_shape() {
        assert_eq!(f32::from_bits(SYNC_TABLE[0]), 1.0);
        assert_eq!(f32::from_bits(SYNC_TABLE[128]), 16.0);
        assert_eq!(SYNC_TABLE[257], 0x3586_37BD);
        assert!(SYNC_TABLE[..128]
            .windows(2)
            .all(|w| f32::from_bits(w[1]) > f32::from_bits(w[0])));
    }
}
