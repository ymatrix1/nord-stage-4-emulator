#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_descending_and_matches_its_fingerprint() {
        assert!(FW_DELAY_TABLE.windows(2).all(|w| w[0] >= w[1]));
        assert_eq!(FW_DELAY_TABLE[0], 16383);
        assert_eq!(FW_DELAY_TABLE[20], 16256);
        assert_eq!(FW_DELAY_TABLE[1499], 2);
        assert_eq!(FW_DELAY_TABLE[1500], 0);
        let mut h: u64 = 0xcbf2_9ce4_8422_2325;
        for v in FW_DELAY_TABLE {
            for b in v.to_le_bytes() {
                h ^= u64::from(b);
                h = h.wrapping_mul(0x0000_0100_0000_01b3);
            }
        }
        assert_eq!(h, FW_DELAY_TABLE_FNV);
    }
}
