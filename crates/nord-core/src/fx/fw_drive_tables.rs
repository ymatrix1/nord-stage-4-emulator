/// The words of a table as floats (evaluated at compile time, so the tables live in read-only data).
const fn floats<const N: usize>(words: &[u32; N]) -> [f32; N] {
    let mut out = [0.0; N];
    let mut i = 0;
    while i < N {
        out[i] = f32::from_bits(words[i]);
        i += 1;
    }
    out
}

/// [`A_WORDS`] as floats.
pub(super) static A: [f32; 129] = floats(&A_WORDS);
/// [`B_WORDS`] as floats.
pub(super) static B: [f32; 129] = floats(&B_WORDS);
/// [`C_WORDS`] as floats.
pub(super) static C: [f32; 1025] = floats(&C_WORDS);
/// Index of `C` for the field value 0.
pub(super) const C_CENTER: usize = 512;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_hold_the_documented_shapes() {
        assert_eq!((A.len(), B.len(), C.len()), (129, 129, 1025));
        assert!(A.windows(2).all(|w| w[1] >= w[0]), "A rises");
        assert!(B.windows(2).all(|w| w[1] <= w[0]), "B falls");
        assert_eq!(C[C_CENTER], 0.0);
        assert!((C[C_CENTER + 512] - 0.3125).abs() < 1e-5);
        assert!((C[0] + 1.0).abs() < 1e-6, "the negative half reaches -1.0");
        assert!((A[0] - 0.003_665).abs() < 1e-5 && (A[128] - 0.697_96).abs() < 1e-5);
    }
}
