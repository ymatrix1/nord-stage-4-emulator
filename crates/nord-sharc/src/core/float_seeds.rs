/// Seed mantissa fraction (8 bits) of `1/x` for the 7-bit index `index`.
pub fn recip_seed(index: u32) -> u32 {
    u32::from(RECIPS_SEED[index as usize & 0x7F])
}

/// Seed mantissa fraction (8 bits) of `1/sqrt(x)` for the exponent parity and a 6-bit index.
pub fn rsqrt_seed(odd: bool, index: u32) -> u32 {
    u32::from(RSQRTS_SEED[usize::from(odd)][index as usize & 0x3F])
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::core::float::Mode;
    use crate::core::float_misc::{recips, rsqrts};

    const CSV: &str = include_str!("../../../../docs/research/sharc-seeds/seeds_full.csv");
    const FLAGS: &str =
        include_str!("../../../../docs/research/sharc-seeds/seeds_specials_flags.csv");
    const M: Mode = Mode {
        trunc: false,
        r32: false,
        sat: false,
    };

    fn hex(s: &str) -> u64 {
        u64::from_str_radix(s, 16).unwrap()
    }

    #[test]
    fn seed_tables_match_every_measured_row() {
        let mut rows = 0;
        for line in CSV.lines().skip(1) {
            let c: Vec<u64> = line.split(',').map(hex).collect();
            let a = c[0] << 8;
            assert_eq!(recips(a, M).v >> 8, c[1], "RECIPS {:08x}", c[0]);
            assert_eq!(rsqrts(a, M).v >> 8, c[2], "RSQRTS {:08x}", c[0]);
            rows += 1;
        }
        assert_eq!(rows, 22 * 256 + 12);
    }

    #[test]
    fn measured_flags_of_the_special_inputs() {
        // ASTAT: AZ 0x1, AV 0x2, AN 0x4, AI 0x20 (the other bits are constant in the dump)
        let bits = |o: crate::core::float::Out| {
            u64::from(o.az) | u64::from(o.av) << 1 | u64::from(o.an) << 2 | u64::from(o.ai) << 5
        };
        let mut n = 0;
        for line in FLAGS.lines().skip(1) {
            let c: Vec<u64> = line.split(',').map(hex).collect();
            let a = c[0] << 8;
            assert_eq!(bits(recips(a, M)), c[1] & 0x27, "RECIPS flags {:08x}", c[0]);
            assert_eq!(bits(rsqrts(a, M)), c[2] & 0x27, "RSQRTS flags {:08x}", c[0]);
            n += 1;
        }
        assert_eq!(n, 12);
    }

    #[test]
    fn tables_have_expected_shape() {
        assert_eq!(recip_seed(0), 0xFF);
        assert_eq!(recip_seed(127), 0x00);
        assert_eq!(rsqrt_seed(false, 0), RSQRTS_SEED[0][0].into());
        assert_ne!(rsqrt_seed(true, 5), rsqrt_seed(false, 5));
    }
}
