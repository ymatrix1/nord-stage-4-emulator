//! Rust source of the generated AOT module (`sharc-aot --hot/--ranges`): one function and one
//! code snapshot per lowered block, plus the `blocks()` table `aot_hot.rs` includes at build time
//! (`NORD_SHARC_AOT_HOT=<file>`). Generated text is derived from firmware and never committed.
use super::aot_lower::{AotTier, Item, Lowered, LoweredOp, MIN_BATCH};
use super::decode_cache::ComputeOp;
use super::Core;
use std::fmt::Write;

fn kern_name(tier: AotTier) -> &'static str {
    match tier {
        AotTier::Pe => "Exact",
        AotTier::Guarded => "Guarded",
        AotTier::Approx => "Approx",
    }
}

/// Statements of one native batch, run on a [`Pe`](super::aot_pe::Pe) named `pe`.
fn emit_batch(out: &mut String, ops: &[LoweredOp]) {
    for &op in ops {
        match op {
            LoweredOp::Compute(ComputeOp::Nop) => {}
            LoweredOp::Compute(c) => {
                let _ = writeln!(out, "    pe.exec(ComputeOp::{c:?});");
            }
            LoweredOp::LoadImm { reg, value } => {
                let _ = writeln!(out, "    pe.load_imm({reg}, 0x{value:08x});");
            }
            LoweredOp::RegMove { src, dst, compute } => {
                let _ = writeln!(out, "    let m = pe.move_src({src});");
                if let Some(c) = compute {
                    let _ = writeln!(out, "    pe.exec(ComputeOp::{c:?});");
                }
                let _ = writeln!(out, "    pe.move_dst({dst}, m);");
            }
            LoweredOp::Shift { op, n, x, ry } => {
                let _ = writeln!(out, "    pe.shift(0x{op:x}, {n}, {x}, 0x{ry:08x});");
            }
        }
    }
}

/// The module text for `blocks` (indexes name the generated functions).
pub(super) fn emit_module(blocks: &[Lowered], tier: AotTier) -> String {
    let mut out = String::new();
    let kern = kern_name(tier);
    let _ = writeln!(
        out,
        "// Generated by `sharc-aot --hot`; derived from firmware: never commit this file."
    );
    for i in [
        "crate::core::aot_hot::AotBlock",
        "crate::core::aot_native::Kern",
        "crate::core::aot_pe::Pe",
        "crate::core::decode_cache::ComputeOp",
        "crate::core::{Core, Fault}",
    ] {
        let _ = writeln!(out, "use {i};");
    }
    for (bi, b) in blocks.iter().enumerate() {
        let code: Vec<String> = b
            .code
            .iter()
            .flat_map(|p| p.to_le_bytes())
            .map(|byte| format!("0x{byte:02x}"))
            .collect();
        let _ = writeln!(
            out,
            "static CODE_{bi}: [u8; {}] = [{}];",
            code.len(),
            code.join(", ")
        );
        let mut body = String::new();
        for (ii, item) in b.items.iter().enumerate() {
            match item {
                Item::Batch(ops) => {
                    let _ = writeln!(
                        out,
                        "#[inline(always)]\n#[allow(unused_variables)]\nfn b{bi}_{ii}(pe: &mut Pe) {{"
                    );
                    emit_batch(&mut out, ops);
                    let _ = writeln!(out, "}}");
                    let _ = writeln!(
                        body,
                        "    {{ let mut pe = Pe::load(core, false).with_kern(Kern::{kern}); b{bi}_{ii}(&mut pe); pe.store(core); }}"
                    );
                    let _ = writeln!(
                        body,
                        "    if simd {{ let mut pe = Pe::load(core, true).with_kern(Kern::{kern}); b{bi}_{ii}(&mut pe); pe.store(core); }}"
                    );
                    let _ = writeln!(body, "    core.steps += {};", ops.len());
                }
                Item::Interp { pc, next } => {
                    let _ = writeln!(
                        body,
                        "    if core.aot_item(0x{pc:x}, &sig, 0x{next:x})? {{ return Ok(()); }}"
                    );
                }
            }
        }
        let _ = writeln!(
            out,
            "#[allow(unused_variables)]\nfn run_{bi}(core: &mut Core) -> Result<(), Fault> {{\n    let sig = core.aot_sig();\n    let simd = core.simd();\n{body}    core.pc = 0x{:x};\n    Ok(())\n}}",
            b.exit
        );
    }
    let _ = writeln!(out, "static BLOCKS: [AotBlock; {}] = [", blocks.len());
    for (bi, b) in blocks.iter().enumerate() {
        let native: u32 = b
            .items
            .iter()
            .map(|i| match i {
                Item::Batch(o) => o.len() as u32,
                Item::Interp { .. } => 0,
            })
            .sum();
        let _ = writeln!(
            out,
            "    AotBlock {{ start: 0x{:x}, last: 0x{:x}, steps: {}, native: {native}, code: &CODE_{bi}, run: run_{bi} }},",
            b.start, b.last, b.steps
        );
    }
    let _ = writeln!(out, "];");
    let _ = writeln!(
        out,
        "pub(super) fn blocks() -> &'static [AotBlock] {{\n    &BLOCKS\n}}"
    );
    out
}

impl Core {
    /// Rust source of the AOT module for the straight-line ranges `(start, last)` (instruction
    /// starts); see [`Core::enable_aot_hot`] for how it is used. Native runs shorter than
    /// `MIN_BATCH` stay interpreter items.
    pub fn emit_hot_blocks_rust(
        &self,
        ranges: &[(u32, u32)],
        tier: AotTier,
    ) -> Result<String, String> {
        let blocks = ranges
            .iter()
            .map(|&(s, l)| self.lower_hybrid(s, l, MIN_BATCH))
            .collect::<Result<Vec<_>, _>>()?;
        Ok(emit_module(&blocks, tier))
    }

    /// Single-range form of [`Core::emit_hot_blocks_rust`] (the `--hot START LAST` CLI).
    pub fn emit_hot_block_rust(
        &self,
        start: u32,
        last: u32,
        tier: AotTier,
    ) -> Result<String, String> {
        self.emit_hot_blocks_rust(&[(start, last)], tier)
    }
}

#[cfg(test)]
mod tests {
    use super::super::support::core_with;
    use super::*;

    fn imm() -> [u16; 3] {
        [0x0f0e, 0x3f80, 0x0000] // R14 = 0x3f800000
    }

    #[test]
    fn module_has_batches_interp_items_and_a_blocks_table() {
        let mut p = Vec::new();
        for _ in 0..3 {
            p.extend_from_slice(&imm());
        }
        p.push(0x9410); // R0 = DM(I2, M0): interpreter item
        let c = core_with(&p);
        let last = c.pc + 9;
        let src = c
            .emit_hot_blocks_rust(&[(c.pc, last), (c.pc, c.pc + 6)], AotTier::Approx)
            .unwrap();
        assert!(src.contains("pe.load_imm(14, 0x3f800000);"), "{src}");
        assert!(src.contains("Kern::Approx"), "{src}");
        assert!(src.contains("core.aot_item(0x"), "{src}");
        assert!(src.contains("static BLOCKS: [AotBlock; 2]"), "{src}");
        assert!(src.contains("native: 3"), "{src}");
        assert!(src.contains("core.steps += 3;"), "{src}");
        assert!(src.contains("pub(super) fn blocks()"), "{src}");
    }

    #[test]
    fn single_range_form_and_unlowerable_range_errors() {
        let c = core_with(&[0x073e, 0x00ff, 0xfffa]); // JUMP
        assert!(c.emit_hot_block_rust(c.pc, c.pc, AotTier::Pe).is_err());
        let mut p = Vec::new();
        for _ in 0..3 {
            p.extend_from_slice(&imm());
        }
        let c = core_with(&p);
        let src = c.emit_hot_block_rust(c.pc, c.pc + 6, AotTier::Pe).unwrap();
        assert!(
            src.contains("Kern::Exact") && src.contains("steps: 3"),
            "{src}"
        );
    }
}
